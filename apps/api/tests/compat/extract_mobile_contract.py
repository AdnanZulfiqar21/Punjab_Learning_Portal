"""Write `mobile_<label>.json`: the operations the mobile app at a commit calls, with the schemas it was built against.

Used by tests/test_upgrade_compatibility.py (P19.S3.T1, MIGRATION-COMPAT-01). Run from the repository root:
    python apps/api/tests/compat/extract_mobile_contract.py 362db5b 2026-10-10
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any


def _show(commit: str, path: str) -> str:
    return subprocess.run(  # noqa: S603 - git with fixed arguments
        ["git", "show", f"{commit}:{path}"],  # noqa: S607
        capture_output=True,
        text=True,
        encoding="utf8",
        check=True,
    ).stdout


def _template(text: str, i: int) -> tuple[str, int]:
    """text[i] is a backtick: the literal with each ${...} replaced by {}, and the index after the closing backtick."""
    out, i = [], i + 1
    while text[i] != "`":
        if text.startswith("${", i):
            depth, i = 1, i + 2
            while depth:
                c = text[i]
                if c == "`":
                    _, i = _template(text, i)
                    continue
                if c in "\"'":
                    i = text.index(c, i + 1) + 1
                    continue
                depth += {"{": 1, "}": -1}.get(c, 0)
                i += 1
            out.append("{}")
        else:
            out.append(text[i])
            i += 1
    return "".join(out), i + 1


def calls(src: str) -> set[tuple[str, str]]:
    found = set()
    for m in re.finditer(r"(?<![A-Za-z])(request|getJSON)<", src):
        i, depth = m.end(), 1
        while depth:  # the type argument may nest <...>
            depth += {"<": 1, ">": -1}.get(src[i], 0)
            i += 1
        if src[i] != "(":
            continue
        i += 1
        while src[i].isspace():
            i += 1
        if src[i] == '"':
            j = src.index('"', i + 1)
            path, i = src[i + 1 : j], j + 1
        elif src[i] == "`":
            path, i = _template(src, i)
        else:
            continue  # the request helper itself
        depth, k = 1, i
        while depth:
            depth += {"(": 1, ")": -1}.get(src[k], 0)
            k += 1
        method = re.search(r'method:\s*"([A-Z]+)"', src[i:k])
        verb = method.group(1).lower() if m.group(1) == "request" and method else "get"
        path = path.split("?")[0]
        if path.endswith("{}") and not path.endswith("/{}"):
            path = path[:-2]  # an optional query string built in an expression
        found.add((verb, path))
    return found


def _refs(node: Any) -> list[str]:
    if isinstance(node, dict):
        return [v.rsplit("/", 1)[-1] for k, v in node.items() if k == "$ref"] + [
            r for k, v in node.items() if k != "$ref" for r in _refs(v)
        ]
    if isinstance(node, list):
        return [r for v in node for r in _refs(v)]
    return []


def main(commit: str, label: str) -> None:
    spec = json.loads(_show(commit, "packages/contracts/openapi.json"))
    by_shape = {
        (method, re.sub(r"\{[^}]*\}", "{}", path)): path for path, ops in spec["paths"].items() for method in ops
    }
    operations, unmatched = [], []
    for method, path in sorted(calls(_show(commit, "apps/mobile/src/lib/api.ts"))):
        real = by_shape.get((method, path))
        if real is None:
            unmatched.append(f"{method.upper()} {path}")  # dev-only routes are not in the published contract
            continue
        op = spec["paths"][real][method]
        operations.append(
            {
                "method": method,
                "path": real,
                "parameters": op.get("parameters", []),
                "requestBody": op.get("requestBody"),
                "responses": {k: v for k, v in op.get("responses", {}).items() if k.startswith("2")},
            }
        )
    schemas: dict[str, Any] = {}
    todo = _refs(operations)
    while todo:
        name = todo.pop()
        if name not in schemas:
            schemas[name] = spec["components"]["schemas"][name]
            todo.extend(_refs(schemas[name]))
    out = {
        "about": (
            "Oldest supported mobile client contract (P19.S3.T1, MIGRATION-COMPAT-01): the operations the mobile app "
            f"at commit {commit} ({label}) calls, with the request and response schemas it was built against. "
            "Generated by extract_mobile_contract.py; do not edit."
        ),
        "commit": commit,
        "unmatched": unmatched,
        "operations": operations,
        "schemas": dict(sorted(schemas.items())),
    }
    dest = Path(__file__).with_name(f"mobile_{label}.json")
    dest.write_text(json.dumps(out, indent=1) + "\n", encoding="utf8", newline="\n")
    sys.stdout.write(f"{len(operations)} operations, {len(schemas)} schemas; not in the contract: {unmatched}\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
