def test_seal_requires_completeness_and_returns_one_receipt(
    client: TestClient, published_written: dict[str, Any]
) -> None:
    who = _learner(client)
    a = _start(client, who, published_written["chapter"], writing_minutes=20)
    p1 = _upload(client, who, a["id"], _png(seed=4)).json()["pages"][0]["id"]
    m = _map(client, who, a, {"1:a": {"pages": [p1]}}).json()
    incomplete = _seal(client, who, a["id"], m["manifest_revision"])
    assert incomplete.status_code == 422 and incomplete.json()["missing"] == ["1:b"]
    m = _map(client, who, m, {"1:a": {"pages": [p1]}, "1:b": {"unanswered": True}}).json()
    key = uuid.uuid4().hex
    sealed = _seal(client, who, a["id"], m["manifest_revision"], key)
    assert sealed.status_code == 200 and not sealed.json()["replay"]
    receipt = sealed.json()["receipt"]
    assert receipt["answered_slots"] == 1 and receipt["unanswered_slots"] == 1
    replay = _seal(client, who, a["id"], m["manifest_revision"], key)
    assert replay.json()["receipt"] == receipt and replay.json()["replay"]
    assert _seal(client, who, a["id"], m["manifest_revision"] + 5, key).status_code == 409  # same key, changed payload
    assert _seal(client, who, a["id"], m["manifest_revision"]).status_code == 409  # already sealed
    assert _upload(client, who, a["id"], _png(seed=5)).status_code == 409  # no post-seal edits
    assert _map(client, who, m, {"1:a": {"unanswered": True}, "1:b": {"unanswered": True}}).status_code == 409
    # The exact retry still returns the receipt after U.
    _shift(a["id"], cutoff_offset_s=-60)
    assert _seal(client, who, a["id"], m["manifest_revision"], key).json()["receipt"] == receipt


def test_nothing_is_admitted_after_the_upload_cutoff(client: TestClient, published_written: dict[str, Any]) -> None:
    who = _learner(client)
    a = _start(client, who, published_written["chapter"], writing_minutes=20)
    p1 = _upload(client, who, a["id"], _png(seed=6)).json()["pages"][0]["id"]
    m = _map(client, who, a, {"1:a": {"pages": [p1]}, "1:b": {"pages": [p1]}}).json()  # one page may cover two parts
    _shift(a["id"], cutoff_offset_s=-0.001)
    late = _seal(client, who, a["id"], m["manifest_revision"])
    assert late.status_code == 409 and late.json()["attempt_status"] == "expired"
    resumed = client.get(f"/v1/written-attempts/{a['id']}", headers=who.headers).json()
    assert resumed["status"] == "expired" and resumed["receipt"] is None and len(resumed["pages"]) == 1  # honest
    assert _upload(client, who, a["id"], _png(seed=7)).status_code == 409


def test_seal_detects_tampered_evidence(client: TestClient, published_written: dict[str, Any]) -> None:
    from portal_api.modules.written import storage

    who = _learner(client)
    a = _start(client, who, published_written["chapter"])
    up = _upload(client, who, a["id"], _png(seed=8)).json()["pages"][0]
    m = _map(client, who, a, {"1:a": {"pages": [up["id"]]}, "1:b": {"unanswered": True}}).json()
    path = storage.get_store().root / f"{a['id']}/{up['file_id']}/original"
    path.write_bytes(path.read_bytes() + b"tampered")
    r = _seal(client, who, a["id"], m["manifest_revision"])
    assert r.status_code == 409 and "integrity check" in r.json()["detail"]
