def test_uploads_are_private_validated_and_deduplicated_within_the_attempt(
    client: TestClient, published_written: dict[str, Any]
) -> None:
    owner, other = _learner(client), _learner(client)
    a = _start(client, owner, published_written["chapter"])
    first = _upload(client, owner, a["id"], _png(seed=1))
    assert first.status_code == 201 and not first.json()["duplicate"]
    again = _upload(client, owner, a["id"], _png(seed=1))
    assert again.json()["duplicate"] and again.json()["pages"][0]["id"] == first.json()["pages"][0]["id"]
    bad = _upload(client, owner, a["id"], b"not an image")
    assert bad.status_code == 422 and "JPEG, PNG or PDF" in bad.json()["detail"]
    page_id = first.json()["pages"][0]["id"]
    got = client.get(f"/v1/written-attempts/{a['id']}/pages/{page_id}", headers=owner.headers)
    assert got.status_code == 200 and got.headers["cache-control"] == "private, no-store"
    assert got.headers["content-type"] == "image/png" and got.content.startswith(PNG_SIGNATURE)  # the preview
    assert client.get(f"/v1/written-attempts/{a['id']}/pages/{page_id}", headers=other.headers).status_code == 404
    assert _upload(client, other, a["id"], _png(seed=2)).status_code == 404


def test_mapping_uses_revision_concurrency(client: TestClient, published_written: dict[str, Any]) -> None:
    who = _learner(client)
    a = _start(client, who, published_written["chapter"])
    page = _upload(client, who, a["id"], _png(seed=3)).json()["pages"][0]["id"]
    ok = _map(client, who, a, {"1:a": {"pages": [page]}})
    assert ok.status_code == 200 and ok.json()["manifest_revision"] == 1
    stale = _map(client, who, a, {"1:b": {"pages": [page]}}, revision=0)
    assert stale.status_code == 409 and stale.json()["current"]["revision"] == 1
    invalid = _map(client, who, ok.json(), {"1:a": {"pages": [page], "unanswered": True}, "9:z": {"pages": []}})
    assert invalid.status_code == 422 and len(invalid.json()["errors"]) == 2


