PNG_SIGNATURE = bytes([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])


def _png(w: int = 1200, h: int = 1600, seed: int = 0) -> bytes:
    """A real, fully decodable PNG (a flat synthetic image; the seed makes its bytes unique)."""
    from PIL import Image

    buf = io.BytesIO()
    Image.new("L", (w, h), color=seed % 256).save(buf, format="PNG")
    return buf.getvalue()


def _pdf(pages: int = 1, seed: int = 0) -> bytes:
    """A real PDF with `pages` blank A4 pages (the seed is stored in the metadata to make the bytes unique)."""
    from pypdf import PdfWriter

    w = PdfWriter()
    for _ in range(pages):
        w.add_blank_page(595, 842)
    w.add_metadata({"/Title": f"fixture-{seed}"})
    buf = io.BytesIO()
    w.write(buf)
    return buf.getvalue()


# ------------------------------------------------------------------ fixtures
def _learner(client: TestClient) -> Staff:
    """A learner with the one-time free trial started (practice and written tests need an active plan)."""
    with get_sessionmaker()() as db:
        who = Staff(client, db, [])
    assert client.post("/v1/me/trial", headers=who.headers).status_code == 200
    return who


def _form(client: TestClient, who: Staff, chapter: str, **extra: Any) -> Any:
    body = {"grade": 12, "subject": "chemistry", "chapter_ids": [chapter], "question_count": 1, **extra}
    return client.post("/v1/written/forms", headers={**who.headers, "Idempotency-Key": uuid.uuid4().hex}, json=body)


def _start(client: TestClient, who: Staff, chapter: str, **extra: Any) -> dict[str, Any]:
    f = _form(client, who, chapter, **extra)
    assert f.status_code == 201, f.text
    a = client.post(f"/v1/written/forms/{f.json()['id']}/attempt", headers=who.headers)
    assert a.status_code == 200, a.text
    return dict(a.json())


def _upload(client: TestClient, who: Staff, attempt_id: str, data: bytes) -> Any:
    return client.post(
        f"/v1/written-attempts/{attempt_id}/pages",
        headers={**who.headers, "Content-Type": "application/octet-stream"},
        content=data,
    )


def _map(
    client: TestClient, who: Staff, attempt: dict[str, Any], slots: dict[str, Any], revision: int | None = None
) -> Any:
    return client.put(
        f"/v1/written-attempts/{attempt['id']}/manifest",
        headers=who.headers,
        json={"expected_revision": attempt["manifest_revision"] if revision is None else revision, "slots": slots},
    )


def _seal(client: TestClient, who: Staff, attempt_id: str, revision: int, key: str | None = None) -> Any:
    return client.post(
        f"/v1/written-attempts/{attempt_id}/seal",
        headers=who.headers,
        json={"idempotency_key": key or uuid.uuid4().hex, "expected_revision": revision},
    )


def _shift(attempt_id: str, *, cutoff_offset_s: float) -> None:
    with get_sessionmaker()() as db:
        db.execute(
            text(
                "update written_attempt set upload_cutoff_at = clock_timestamp() + make_interval(secs => :c) "
                "where id = :id"
            ),
            {"c": cutoff_offset_s, "id": attempt_id},
        )
        db.commit()


