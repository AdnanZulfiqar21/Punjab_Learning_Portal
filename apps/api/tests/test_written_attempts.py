def test_unstaffed_or_unreviewed_written_practice_is_never_offered(
    client: TestClient, published_written: dict[str, Any]
) -> None:
    who = _learner(client)
    av = client.get("/v1/written/availability?grade=12&subject=chemistry", headers=who.headers).json()
    assert av["review_staffed"] is True
    assert next(c for c in av["chapters"] if c["chapter_id"] == published_written["chapter"])["questions"] == 2
    phys = client.get("/v1/written/availability?grade=11&subject=mathematics", headers=who.headers).json()
    assert all(c["questions"] == 0 for c in phys["chapters"])
    too_many = _form(client, who, published_written["chapter"], question_count=3)
    assert too_many.status_code == 422 and too_many.json()["available"] == 2


def test_attempt_shows_questions_and_marks_but_never_rubrics(
    client: TestClient, published_written: dict[str, Any]
) -> None:
    who = _learner(client)
    a = _start(client, who, published_written["chapter"], writing_minutes=30)
    assert a["status"] == "active" and a["writing_deadline_at"] and a["upload_allowance_s"] == 600
    item = a["items"][0]
    assert [s["key"] for s in item["slots"]] == ["1:a", "1:b"] and item["max_units"] == 500
    assert "criteria" not in str(a) and "rubric" not in str(a).lower()


